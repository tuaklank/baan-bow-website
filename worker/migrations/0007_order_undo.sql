-- ย้อนกลับคำสั่งออเดอร์โบว์ล่าสุดหนึ่งครั้ง
-- เจ้าของร้านพิมพ์ผิดแล้วได้แถวใหม่มาเป็นสิบ (เลขออเดอร์ถูกอ่านเป็นจำนวนชิ้น)
-- จึงต้องมีทางถอยที่พิมพ์คำเดียวจบ: "ย้อนกลับ"
--
-- เก็บชุดเดียวต่อผู้ใช้ คำสั่งออเดอร์ครั้งถัดไปเขียนทับ — ตั้งใจให้ย้อนได้ครั้งเดียว
-- payload เป็น JSON: { created: [เลขที่จดขึ้นมาใหม่], before: [แถวเดิมทั้งแถวก่อนถูกแก้/ลบ] }
CREATE TABLE order_undo (
  user_id    TEXT PRIMARY KEY,
  label      TEXT NOT NULL,                         -- บอกเจ้าของร้านว่าย้อนอะไรไป เช่น "จดออเดอร์ #9–#14 (6 ชิ้น)"
  payload    TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
